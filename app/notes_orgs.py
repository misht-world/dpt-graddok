def _simplify(text: str) -> str:
    """Приводит строку к виду, удобному для сравнения."""
    text = text.lower().replace("ё", "е")
    text = re.sub(r'[«»"„“]', " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def _district(text: str) -> Optional[str]:
    """Достаёт название района из «администрации ... района»."""
    match = re.search(r"([А-ЯЁ][а-яё]+)ск(?:ого|ий|ом|ому|ая|ой)\s+район", text)
    if match:
        return match.group(1) + "ский"

    # Вариант «Администрация Пушкинского района» с переносом или сокращением
    match = re.search(r"администрац\w*\s+([А-ЯЁ][а-яё]+)ск", text, re.IGNORECASE)
    if match:
        return match.group(1).capitalize() + "ский"
    return None


def normalize_organization(raw: Optional[str]) -> Optional[str]:
    """
    Возвращает сокращение организации или исходную строку, если не опознали.

    >>> normalize_organization("КОМИТЕТ ПО ТРАНСПОРТУ")
    'КТ'
    >>> normalize_organization("Комитет по природопользованию, охране окружающей среды")
    'КПООС'
    >>> normalize_organization("Администрация Пушкинского района Санкт-Петербурга")
    'РА Пушкинский'
    """
    if not raw:
        return raw

    cleaned = re.sub(r"\s+", " ", raw).strip()
    simple = _simplify(cleaned)

    # Уже сокращение: «КРТИ», «КТ СПб», «КППИ»
    token = re.match(r"^([А-ЯЁ]{1,3}[а-яё]{0,3}[А-ЯЁи]{0,5})(\s+спб)?$", cleaned, re.IGNORECASE)
    if token:
        candidate = token.group(1)
        candidate = ABBREVIATION_ALIASES.get(candidate.upper(), candidate)
        for abbr in ORGANIZATIONS:
            if candidate.upper() == abbr.upper():
                return abbr

    # Районная администрация
    if "администрац" in simple:
        district = _district(cleaned)
        return f"РА {district}" if district else "РА"

    for abbr, groups in RULES:
        if all(any(variant in simple for variant in group) for group in groups):
            return abbr

    return cleaned
